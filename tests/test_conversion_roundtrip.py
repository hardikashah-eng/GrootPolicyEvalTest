"""HDF5 -> LeRobot -> HDF5 round trip (C5) and sim replay (C6) on SYNTHETIC Isaac Lab-style demos.

The demos are generated by a tiny first-order joint model, and the mock replayer below runs the same
model, so a clean pipeline replays exactly and each injected fault shows up where it should.
"""

import json
import shutil

import numpy as np
import pandas as pd
import pytest

h5py = pytest.importorskip("h5py")
cv2 = pytest.importorskip("cv2")
if shutil.which("ffmpeg") is None:  # lossless reference encode and pix_fmt probing need the ffmpeg CLI
    pytest.skip("ffmpeg not installed", allow_module_level=True)

from groot_eval import conversion_fidelity as cf  # noqa: E402
from groot_eval import conversion_roundtrip as rt  # noqa: E402

D, T, H, W, FPS = 7, 40, 64, 80, 20
MAPPING = {
    "episodes": "data/demo_*", "fps": FPS, "task_attr": "task",
    "state": [{"key": "obs/joint_pos", "modality": "joint_pos"}, {"key": "obs/joint_vel", "modality": "joint_vel"}],
    "action": [{"key": "actions", "modality": "arm"}],
    "video": {"front": "obs/front_rgb"},
    "ignore": ["states/*", "initial_state/*", "obs/datagen_info/*"],
}
Q0 = "initial_state/articulation/robot/joint_position"
QS = "states/articulation/robot/joint_position"


class Model:
    """q[t+1] = q[t] + gain * (a[t] - q[t]); renders one disc per joint on a smooth background."""

    def __init__(self, gain=0.3, noise=0.0, seed=0, bgr=False):
        self.gain, self.noise, self.bgr = gain, noise, bgr
        self.rng = np.random.default_rng(seed)
        yy, xx = np.mgrid[0:H, 0:W]
        self.yy, self.xx = yy, xx
        self.bg = np.stack([xx * 200 / W + 30, yy * 200 / H + 30, (xx + yy) * 100 / (W + H) + 60], -1)

    def step(self, q, a):
        q = q + self.gain * (a - q)
        return q + self.rng.normal(0, self.noise, q.shape) if self.noise else q

    def render(self, q):
        f = self.bg.copy()
        for i in range(D):
            cx, cy = W * (i + 0.5) / D, H / 2 + H / 3 * np.tanh(q[i])
            f[(self.xx - cx) ** 2 + (self.yy - cy) ** 2 < 16] = [(60 + 37 * i) % 255, 200 - 20 * i, (90 * i) % 255]
        f = cv2.GaussianBlur(np.clip(f, 0, 255).astype(np.uint8), (5, 5), 1.2)
        return f[..., ::-1].copy() if self.bgr else f


class MockReplayer:
    def __init__(self, model=None):
        self.model = model or Model()

    def replay(self, h5_path, demo, mode, render=False):
        with h5py.File(h5_path, "r") as f:
            g = f["data"][demo]
            q, acts, states = g[Q0][0].astype(float), g["actions"][()].astype(float), g[QS][()].astype(float)
        joints, frames = [], []
        if mode == "actions":
            for a in acts:
                q = self.model.step(q, a)
                joints.append(q.copy())
            return rt.ReplayResult(np.array(joints), success=bool(np.abs(q).max() < 3.0))
        for s in states:
            joints.append(s)
            frames.append(self.model.render(s))
        return rt.ReplayResult(np.array(joints), {"obs/front_rgb": np.stack(frames)})


@pytest.fixture()
def demo(tmp_path):
    path = tmp_path / "demo.hdf5"
    model = Model()
    with h5py.File(path, "w") as f:
        d = f.create_group("data")
        d.attrs["env_args"] = json.dumps({"env_name": "Isaac-Mock-v0", "env_kwargs": {"control_freq": FPS}})
        for i in range(2):
            rng = np.random.default_rng(i)
            q = rng.uniform(-0.5, 0.5, D)
            q0 = q.copy()
            t = np.arange(T)[:, None]
            acts = 0.8 * np.sin(2 * np.pi * t / T * (1 + 0.2 * np.arange(D)) + rng.uniform(0, 6, D))
            qs, imgs = [], []
            for k in range(T):
                qs.append(q.copy())
                imgs.append(model.render(q))
                q = model.step(q, acts[k])
            qs = np.array(qs)
            g = d.create_group(f"demo_{i}")
            g.create_dataset("obs/joint_pos", data=qs)
            g.create_dataset("obs/joint_vel", data=np.gradient(qs, axis=0) * FPS)
            g.create_dataset("actions", data=acts)
            g.create_dataset("obs/front_rgb", data=np.stack(imgs))
            g.create_dataset("obs/ft_wrench", data=rng.normal(size=(T, 6)))
            g.create_dataset(QS, data=qs)
            g.create_dataset(Q0, data=q0[None])
            g.attrs["success"] = True
            g.attrs["task"] = "reach the pose"
            g.attrs["num_samples"] = T
    cfg = rt.load_config(None)
    cfg["mapping"] = MAPPING
    lerobot = cf.convert_hdf5_to_lerobot(path, tmp_path / "ds", MAPPING, fps=FPS)  # h264-lossless
    return path, lerobot, cfg, tmp_path


def _errors(res):
    return [f for f in res.findings if f.level == "error"]


def _with_sidecar(demo):
    path, ds, cfg, tmp = demo
    rt.write_sidecar(path, ds, cfg)
    return path, ds, cfg, tmp


def _rebuilt(demo):
    path, ds, cfg, tmp = _with_sidecar(demo)
    res = rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    return path, ds, cfg, tmp, res


# ---------- C5 round trip ----------

def test_clean_round_trip_is_exact_and_reports_what_cannot_be_rebuilt(demo):
    path, ds, cfg, tmp, res = _rebuilt(demo)
    assert res.status != "fail", rt.roundtrip_markdown([res], str(path), str(ds))
    checks = {f.check: f for f in res.findings}
    assert checks["sidecar"].level == "ok"
    assert checks["obs/joint_pos.values"].level == "ok" and checks["actions.values"].level == "ok"
    assert res.metrics["cameras"]["obs/front_rgb"]["psnr_mean"] > 60  # lossless reference encode
    assert res.metrics["lost"] == ["obs/ft_wrench"]  # neither mapped, ignored nor in the sidecar
    with h5py.File(path) as a, h5py.File(tmp / "rebuilt.hdf5") as b:
        assert np.array_equal(a["data/demo_1"][Q0][()], b["data/demo_1"][Q0][()])
        assert b["data/demo_1/actions"].dtype == a["data/demo_1/actions"].dtype
        assert b["data"].attrs["env_args"] == a["data"].attrs["env_args"]
        assert b["data/demo_0"].attrs["task"] == "reach the pose"


def test_missing_sidecar_fails_with_instructions(demo):
    path, ds, cfg, tmp = demo
    res = rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    assert res.status == "fail" and "convert-sidecar" in _errors(res)[0].detail


def test_sidecar_tamper_detected(demo):
    path, ds, cfg, tmp = _with_sidecar(demo)
    with h5py.File(ds / rt.SIDECAR_DIR / "episode_000001.hdf5", "a") as f:
        f[Q0][0, 0] += 0.1
    res = rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    assert any(f.check == "sidecar.hash" for f in _errors(res))


def test_unit_bug_in_lerobot_fails_values(demo):
    path, ds, cfg, tmp = _with_sidecar(demo)
    for p in sorted((ds / "data").rglob("*.parquet")):
        df = pd.read_parquet(p)
        df["action"] = [np.degrees(np.asarray(v)).astype(np.float32) for v in df["action"]]
        df.to_parquet(p)
    res = rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    assert any(f.check == "actions.values" for f in _errors(res))


def test_lossy_reencode_fails_psnr_and_reports_pix_fmt_ceiling(demo):
    path, ds, cfg, tmp = _with_sidecar(demo)
    for p in sorted((ds / "videos").rglob("*.mp4")):
        frames = np.stack(cf._frames(p))
        cf.write_video(frames, p, FPS, "h264")  # yuv420p, CRF 18
    cfg["gates"]["C5_roundtrip"].update(min_psnr_mean=60.0, min_psnr_p5=55.0)
    res = rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    checks = {f.check: f for f in _errors(res)}
    assert "front.psnr" in checks
    assert "front.pix_fmt" in checks and "yuv420p" in checks["front.pix_fmt"].detail
    assert res.metrics["cameras"]["obs/front_rgb"]["pix_fmt_ceiling_db"] < 60


def test_lossless_rgb_video_has_no_ceiling(demo):
    path, ds, cfg, tmp, res = _rebuilt(demo)
    pix = next(f for f in res.findings if f.check == "front.pix_fmt")
    assert pix.level == "ok" and "no chroma subsampling" in pix.detail


def test_ignored_streams_are_reported(demo):
    path, ds, cfg, tmp = demo
    cfg["sidecar"] = ["initial_state"]  # states/* is ignored and now not kept either
    rt.write_sidecar(path, ds, cfg)
    res = rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    ign = next(f for f in res.findings if f.check == "ignored")
    assert ign.level == "warn" and QS in ign.detail


# ---------- C6 replay ----------

def test_clean_replay_passes(demo):
    path, ds, cfg, tmp, _ = _rebuilt(demo)
    res = rt.check_replay(path, tmp / "rebuilt.hdf5", cfg, MockReplayer(), joint_key="obs/joint_pos")
    assert res.status == "pass", [f.detail for f in res.findings if f.level != "ok"]
    assert res.metrics["demo_0"]["render.front"]["psnr_mean"] == 100.0


def test_replay_blames_the_conversion_for_a_unit_bug(demo):
    path, ds, cfg, tmp = _with_sidecar(demo)
    for p in sorted((ds / "data").rglob("*.parquet")):
        df = pd.read_parquet(p)
        df["action"] = [np.degrees(np.asarray(v)).astype(np.float32) for v in df["action"]]
        df.to_parquet(p)
    rt.check_roundtrip(path, ds, cfg, tmp / "rebuilt.hdf5")
    res = rt.check_replay(path, tmp / "rebuilt.hdf5", cfg, MockReplayer(), joint_key="obs/joint_pos", render=False)
    bad = {f.check.split(".", 1)[1] for f in _errors(res)}
    assert "conversion" in bad and "success" in bad and "source" not in bad


def test_replay_blames_sim_drift_not_the_conversion(demo):
    path, ds, cfg, tmp, _ = _rebuilt(demo)
    res = rt.check_replay(path, tmp / "rebuilt.hdf5", cfg, MockReplayer(Model(gain=0.35)),
                          joint_key="obs/joint_pos", render=False)
    bad = {f.check.split(".", 1)[1] for f in _errors(res)}
    assert "source" in bad and "conversion" not in bad


def test_nondeterministic_sim_warns_and_widens_the_limit(demo):
    path, ds, cfg, tmp, _ = _rebuilt(demo)
    res = rt.check_replay(path, tmp / "rebuilt.hdf5", cfg, MockReplayer(Model(noise=1e-3, seed=3)), render=False)
    assert any(f.check.endswith("determinism") and f.level == "warn" for f in res.findings)
    assert res.metrics["demo_0"]["conversion"]["allowed"] > cfg["gates"]["C6_replay"]["joint_abs"]


def test_render_mismatch_detected(demo):
    path, ds, cfg, tmp, _ = _rebuilt(demo)
    res = rt.check_replay(path, tmp / "rebuilt.hdf5", cfg, MockReplayer(Model(bgr=True)), joint_key="obs/joint_pos")
    assert any(f.check.endswith("front.render") for f in _errors(res))


# ---------- config and CLI ----------

def test_config_shares_mapping_and_keeps_convert_check_strict(tmp_path):
    import yaml

    p = tmp_path / "c.yaml"
    p.write_text(yaml.safe_dump({"mapping": MAPPING, "roundtrip": {"sidecar": ["initial_state"],
                                                                     "gates": {"C5_roundtrip": {"min_psnr_mean": 40}}}}))
    cfg = rt.load_config(p)
    assert cfg["mapping"]["fps"] == FPS and cfg["sidecar"] == ["initial_state"]
    assert cfg["gates"]["C5_roundtrip"]["min_psnr_mean"] == 40
    assert cf.load_config(p)["mapping"]["fps"] == FPS  # convert-check reads the same file unchanged
    p.write_text(yaml.safe_dump({"roundtrip": {"gates": {"C9": {}}}}))
    with pytest.raises(ValueError, match="unknown roundtrip gate"):
        rt.load_config(p)


def test_cli_convert_with_sidecar_roundtrip_and_replay(demo, monkeypatch):
    import sys
    import types

    import yaml
    from groot_eval.twin_cli import main

    path, _, cfg, tmp = demo
    (tmp / "cfg.yaml").write_text(yaml.safe_dump({"mapping": MAPPING}))
    assert main(["convert", "--hdf5", str(path), "--config", str(tmp / "cfg.yaml"), "--fps", str(FPS),
                 "--sidecar", "--out", str(tmp / "ds2")]) == 0
    assert (tmp / "ds2" / rt.SIDECAR_DIR / rt.MANIFEST).exists()
    assert main(["roundtrip", "--hdf5", str(path), "--lerobot", str(tmp / "ds2"), "--config", str(tmp / "cfg.yaml"),
                 "--out", str(tmp / "rt")]) == 0
    assert (tmp / "rt" / "rebuilt.hdf5").exists() and (tmp / "rt" / "roundtrip.md").exists()
    monkeypatch.setitem(sys.modules, "mock_replay_mod", types.SimpleNamespace(Replayer=MockReplayer))
    assert main(["replay-check", "--hdf5", str(path), "--rebuilt", str(tmp / "rt" / "rebuilt.hdf5"),
                 "--config", str(tmp / "cfg.yaml"), "--replayer", "mock_replay_mod:Replayer",
                 "--out", str(tmp / "rp")]) == 0
    shutil.rmtree(tmp / "ds2" / rt.SIDECAR_DIR)
    assert main(["roundtrip", "--hdf5", str(path), "--lerobot", str(tmp / "ds2"), "--config", str(tmp / "cfg.yaml"),
                 "--out", str(tmp / "rt2")]) == 1
